import unittest
import os
import re
import tempfile

from nixglhost import (
    CACHE_VERSION,
    CUDA_DSO_PATTERNS,
    EGL_DSO_PATTERNS,
    GLX_DSO_PATTERNS,
    NVIDIA_DSO_PATTERNS,
    CacheDirContent,
    LibraryPath,
    ResolvedLib,
    create_dso_symlinks,
    unversioned_dso_name,
)


class TestCacheSerializer(unittest.TestCase):
    def test_hostdso_json_golden_test(self):
        lp = LibraryPath(
            glx=[
                ResolvedLib(
                    "dummyglx.so", "/lib", "/lib/dummyglx.so", 1670260550.481498, 1612
                )
            ],
            cuda=[
                ResolvedLib(
                    "dummycuda.so", "/lib", "/lib/dummycuda.so", 2670260550.481498, 2612
                )
            ],
            generic=[
                ResolvedLib(
                    "dummygeneric.so",
                    "/lib",
                    "/lib/dummygeneric.so",
                    3670260550.481498,
                    3612,
                )
            ],
            egl=[
                ResolvedLib(
                    "dummyegl.so", "/lib", "/lib/dummyegl.so", 4670260550.481498, 4612
                )
            ],
            path="/path/to/lib/dir",
        )
        cdc = CacheDirContent([lp])
        json = cdc.to_json()

        self.assertIsNotNone(json)
        golden_cdc = CacheDirContent.from_json(json)
        self.assertEqual(cdc, golden_cdc)
        self.assertEqual(cdc.to_json(), golden_cdc.to_json())

    def test_eq_commut_jsons(self):
        """Checks that object equality is not sensible to JSON keys commutations"""
        cwd = os.path.dirname(os.path.realpath(__file__))
        with open(
            os.path.join(cwd, "..", "tests", "fixtures", "json_permut", "1.json"),
            "r",
            encoding="utf8",
        ) as f:
            cdc_json = f.read()
        with open(
            os.path.join(cwd, "..", "tests", "fixtures", "json_permut", "2.json"),
            "r",
            encoding="utf8",
        ) as f:
            commut_cdc_json = f.read()
        with open(
            os.path.join(
                cwd, "..", "tests", "fixtures", "json_permut", "not-equal.json"
            ),
            "r",
            encoding="utf8",
        ) as f:
            wrong_cdc_json = f.read()
        cdc = CacheDirContent.from_json(cdc_json)
        commut_cdc = CacheDirContent.from_json(commut_cdc_json)
        wrong_cdc = CacheDirContent.from_json(wrong_cdc_json)
        self.assertEqual(cdc, commut_cdc)
        self.assertNotEqual(cdc, wrong_cdc)
        self.assertNotEqual(commut_cdc, wrong_cdc)

    def test_cache_version_mismatch(self):
        """A cache generated by another nix-gl-host version is stale."""
        cdc = CacheDirContent([], version=CACHE_VERSION)
        old_cdc = CacheDirContent([], version=CACHE_VERSION - 1)
        self.assertNotEqual(cdc, old_cdc)
        self.assertEqual(CacheDirContent.from_json(old_cdc.to_json()), old_cdc)
        self.assertNotEqual(CacheDirContent.from_json(old_cdc.to_json()), cdc)


class TestDsoPatterns(unittest.TestCase):
    def matches(self, name):
        return any(
            re.search(p, name)
            for p in NVIDIA_DSO_PATTERNS
            + CUDA_DSO_PATTERNS
            + GLX_DSO_PATTERNS
            + EGL_DSO_PATTERNS
        )

    def test_libcuda_dlopened_dsos(self):
        """The DSOs libcuda dlopens are picked up."""
        for name in [
            "libnvidia-nvvm.so.4",
            "libnvidia-nvvm70.so.4",
            "libnvcuextend.so.1",
            "libnvcucompat.so",
            "libnvidia-ptxjitcompiler.so.1",
            "libnvidia-tileiras.so.615.71.09",
            "libnvidia-gpucomp.so.615.71.09",
            "libnvidia-pkcs11-openssl3.so.615.71.09",
        ]:
            self.assertTrue(self.matches(name), name)


class TestDsoSymlinks(unittest.TestCase):
    def test_unversioned_dso_name(self):
        self.assertEqual(unversioned_dso_name("libnvcuextend.so.1"), "libnvcuextend.so")
        self.assertEqual(
            unversioned_dso_name("libnvidia-egl-gbm.so.1.1.3"), "libnvidia-egl-gbm.so"
        )
        self.assertIsNone(unversioned_dso_name("libnvcucompat.so"))

    def test_create_dso_symlinks(self):
        with tempfile.TemporaryDirectory() as d:
            names = ["libnvcuextend.so.1", "libnvcuextend.so.615.71.09", "libfoo.so"]
            for n in names:
                with open(os.path.join(d, n), "w") as f:
                    f.write(n)
            create_dso_symlinks([os.path.join(d, n) for n in names])
            link = os.path.join(d, "libnvcuextend.so")
            self.assertTrue(os.path.islink(link))
            # Existing files are never overridden.
            for n in names:
                self.assertFalse(os.path.islink(os.path.join(d, n)))
            self.assertEqual(
                sorted(os.listdir(d)), sorted(names + ["libnvcuextend.so"])
            )


if __name__ == "__main__":
    unittest.main()
